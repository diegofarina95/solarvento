export function createI18n(language) {
  const lang = translations[language] ? language : 'es'
  const dictionary = translations[lang]
  const fallback = translations.es

  function t(key, params = {}) {
    const value = resolve(dictionary, key) ?? resolve(fallback, key) ?? key
    return typeof value === 'function' ? value(params) : value
  }

  return {
    language: lang,
    locale: dictionary.locale,
    months: dictionary.months,
    t,
  }
}

function resolve(source, key) {
  return key.split('.').reduce((value, part) => value?.[part], source)
}
